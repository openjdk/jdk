/*
 * @test
 * @bug 8389670
 * @library /test/lib /
 * @summary Test that all the inputs of VectorBitwiseBlendNode are vectors
 * @modules jdk.incubator.vector
 *
 * @run driver ${test.main.class} -DShuffleTests=false -DTest=bm,f --add-modules=jdk.incubator.vector
 */

// The test is a reduced version of the one generated by VectorExpressionFuzzer.java

package compiler.vectorapi;

import compiler.lib.ir_framework.*;
import jdk.incubator.vector.*;

public class TestVectorBitwiseBlendTopInput {
    public static void main(String[] args) {
        TestFramework framework = new TestFramework();
        framework.addFlags(args);
        framework.start();
    }

    Object g = test_17();

    @Test
    Object test_17() {
        return ShortVector.broadcast(ShortVector.SPECIES_128, 0);
    }

    @Test
    Object a() {
        return g;
    }

    Object g(VectorShuffle<?> a) {
        return a;
    }

    @Test
    Object e() {
        return g;
    }

    @Test
    Object f() {
        try {
            return ((LongVector)
                    DoubleVector.broadcast(DoubleVector.SPECIES_256, 0)
                                .convertShape(
                                    VectorOperators.Conversion.ofReinterpret(double.class, long.class),
                                    LongVector.SPECIES_128,
                                    1))
                    .bitwiseBlend(
                        VectorMask.fromArray(LongVector.SPECIES_256,
                                             new boolean[] {true, true, true, true},
                                             0).toLong(),
                        ((LongVector) DoubleVector.broadcast(DoubleVector.SPECIES_512, 0)
                            .convert(VectorOperators.Conversion.ofReinterpret(double.class, long.class), -1))
                            .convertShape(
                                VectorOperators.Conversion.ofCast(long.class, long.class),
                                LongVector.SPECIES_128,
                                ShortVector.broadcast(ShortVector.SPECIES_128, 0).toShuffle().checkIndex(0)));
        } catch (IndexOutOfBoundsException a) {
            return a;
        }
    }

    @Test
    Object b() {
        return g;
    }

    @Test
    Object bm() {
        return DoubleVector.broadcast(DoubleVector.SPECIES_256, 0)
                           .lanewise(
                                VectorOperators.ADD,
                                ((DoubleVector)
                                    LongVector.broadcast(LongVector.SPECIES_512, 0)
                                              .reinterpretShape(DoubleVector.SPECIES_64, 1))
                                    .lane(0));
    }
}
